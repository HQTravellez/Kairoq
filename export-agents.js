// Checks that need no install, server or account: plain Node (node --test).
const TESTS=`// Generated by Kairoq: project checks any developer or AI coding tool can run with \`npm test\`.
// Sign-in, payments and credits run on Kairoq and are tested there; these check the code here.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
function walk(dir) {
  const full = join(root, dir);
  if (!existsSync(full)) return [];
  return readdirSync(full).flatMap((f) => (statSync(join(full, f)).isDirectory() ? walk(join(dir, f)) : [join(dir, f)]));
}
const source = walk('src').filter((p) => /\\.(jsx?|tsx?)$/.test(p) && !/src[\\\\/]kairoq[^\\\\/]*\\.js$/.test(p));
const backend = existsSync(join(root, 'src/backend.json')) ? JSON.parse(read('src/backend.json')) : { collections: {} };

test('every collection the app uses is declared in src/backend.json', () => {
  const declared = new Set(Object.keys(backend.collections || {}));
  for (const file of source) {
    for (const m of read(file).matchAll(/collection\\(\\s*['"]([a-z][a-z0-9_]*)['"]/g)) {
      assert.ok(declared.has(m[1]), file + ' uses collection("' + m[1] + '"), which is not in src/backend.json');
    }
  }
});

test('every local import points at a file that exists', () => {
  for (const file of source) {
    for (const m of read(file).matchAll(/(?:from|import)\\s*\\(?\\s*['"](\\.{1,2}\\/[^'"]+)['"]/g)) {
      const target = resolve(root, dirname(file), m[1]);
      const found = ['', '.js', '.jsx', '.ts', '.tsx', '/index.js', '/index.jsx'].some((ext) => existsSync(target + ext));
      assert.ok(found, file + ' imports ' + m[1] + ', which does not exist');
    }
  }
});

test('no secret keys in the code', () => {
  const secret = /(sk_live_|sk_test_|rk_live_|whsec_)[A-Za-z0-9]{8,}|AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY-----/;
  for (const file of [...source, ...walk('functions')]) assert.doesNotMatch(read(file), secret, file + ' contains what looks like a secret key');
});

const products = (backend.payments && backend.payments.products) || {};
test('plans shown to customers match the products they pay for', { skip: !existsSync(join(root, 'src/saas.config.js')) && 'not a SaaS starter app' }, async () => {
  const { PLANS = [] } = await import(pathToFileURL(join(root, 'src/saas.config.js')).href);
  for (const plan of PLANS) {
    const p = products[plan.product];
    assert.ok(p, 'plan "' + plan.product + '" is not a product in src/backend.json payments');
    if (plan.credits !== undefined) assert.equal(p.credits, plan.credits, 'plan "' + plan.product + '" shows ' + plan.credits + ' credits but adds ' + p.credits);
  }
});

const placeholders = Object.entries(products).filter(([, p]) => /^price_Replace/.test(p.price)).map(([n]) => n);
test('Stripe price ids are real', { skip: placeholders.length > 0 && 'replace the price_Replace… ids in src/backend.json (' + placeholders.join(', ') + ') with your Stripe price ids' }, () => {
  for (const [name, p] of Object.entries(products)) assert.match(p.price, /^price_[A-Za-z0-9]+$/, name);
});
`;

