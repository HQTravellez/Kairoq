"use strict";
// Agent-ready downloads: the code an owner downloads or pushes to GitHub comes with instructions
// for AI coding tools (AGENTS.md, read by Codex, Cursor and others; CLAUDE.md for Claude Code) and
// checks they can run without any setup (npm test). The instructions are written from the app's
// own files, so they name its real pages, collections and features. Kairoq writes these files on
// every push; owners keep their own notes in NOTES.md, which Kairoq never touches.

const ACCESS_NOTE={
 private:"each signed-in user sees only their own records",
 shared:"every signed-in user sees all records",
 "public-read":"anyone reads, signed-in users add",
 public:"anyone reads and adds",
 "submit-only":"anyone adds, nobody reads back (the owner sees them in Kairoq)",
 managed:"anyone reads, only the app's managers change",
 team:"shared by the members of the current team; viewers only read"
};

function config(source){try{return JSON.parse(source["src/backend.json"]||"{}")}catch{return{}}}

// The app's own files, grouped so an agent sees the shape of the project at a glance.
function fileMap(source){
 const paths=Object.keys(source).filter(p=>!/^src\/kairoq[^/]*\.js$/.test(p)).sort();
 const ui=paths.filter(p=>p.startsWith("src/components/ui/"));
 const rest=paths.filter(p=>!p.startsWith("src/components/ui/")&&/^(src|functions|sql)\//.test(p));
 const lines=rest.map(p=>"- `"+p+"`"+(NOTES[p]?": "+NOTES[p]:""));
 if(ui.length)lines.push("- `src/components/ui/`: "+ui.length+" UI kit components (shadcn-style: button, card, dialog, input, tabs…). Reuse them.");
 return lines.join("\n");
}
const NOTES={
 "src/main.jsx":"entry point (renders App)",
 "src/App.jsx":"routes",
 "src/index.css":"design tokens (colours, fonts, radius) between the kairoq:tokens markers, and the font imports",
 "src/backend.json":"what the backend stores and offers (see Backend below)",
 "src/saas.config.js":"product name, words, plans and AI instructions",
 "src/lib/utils.js":"cn() for joining Tailwind classes",
 // The SaaS starter's own files.
 "src/components/AppShell.jsx":"the signed-in frame: needs an account and a team (first-team step), navigation",
 "src/lib/session.js":"useSession() and useTeam() hooks",
 "src/pages/Account.jsx":"sign in, sign up, Google, password reset",
 "src/pages/Home.jsx":"landing page with pricing and questions",
 "src/pages/Workspace.jsx":"the product itself (the AI feature that uses credits)"
};

function backendSection(cfg){
 const out=[];
 const cols=Object.entries(cfg.collections||{});
 if(cols.length){
  out.push("Collections (declare every one here before using it with `collection('name')`):");
  for(const [name,def] of cols){const access=typeof def==="string"?def:def.access;out.push("- `"+name+"` ("+access+"): "+(ACCESS_NOTE[access]||access))}
 }else out.push("No collections yet. Declare one in `src/backend.json` before using `collection('name')`.");
 const on=[];
 if(cfg.ai)on.push("AI (`ai.chat`, `ai.ask`, `ai.extract`)");
 if(cfg.credits)on.push("customer credits: "+(cfg.credits.free||0)+" free, "+(cfg.credits.ai_cost||1)+" per AI request (`credits.mine()`, `credits.buy(product)`; a 402 error means out of credits)");
 if(cfg.payments)on.push("Stripe payments: "+Object.entries(cfg.payments.products||{}).map(([n,p])=>"`"+n+"` ("+(p.mode||"payment")+(p.credits?", +"+p.credits+" credits":"")+")").join(", "));
 if(Object.values(cfg.collections||{}).some(d=>(typeof d==="string"?d:d.access)==="team"))on.push("teams (`teams.*`; team records follow the current team)");
 if(cfg.storage)on.push("file uploads (`storage.upload`)");
 if(cfg.email)on.push("email (`email.send` to 'owner' or 'me')");
 if(cfg.automations)on.push("automations (functions run on a schedule or on record changes)");
 if(on.length)out.push("","Turned on: "+on.join("; ")+".");
 return out.join("\n");
}

