"use strict";
// The craft check: after the first build of a site, Kairoq opens the real page (desktop and phone),
// measures the "made by AI" giveaways (design-tells.js) and sends them back to the builder with the
// exact fixes, measures again, then asks an AI that can see the screenshots whether a top design
// studio would ship it and what still looks generated, and fixes that once. All free, before the
// owner sees the site. The owner gets one plain line about it.

const TELLS=new Set(['norm-h1','norm-words','norm-radius','norm-shadows','norm-sections','eyebrow','dots','arrows','accent-word','gradient-text','blobs','emoji','card-grids','icon-cards','round','shadows','boxed','fonts','pill','filler','sections','numbers','made-up-number','faded-headline','touch-targets','mobile-text','icon-labels','form-labels','image-alt','heading-order','horizontal-overflow','fixed-safe-area']);

// The giveaways on the screenshots, plus big numbers the owner never gave.
function found(pictures,facts,type){
 const all=[];
 // How the page compares with the best sites of its kind (desktop measurements, craft-norms.js).
 const desk=(pictures||[]).find(p=>p.name==='desktop'&&p.metrics);
 if(desk)for(const i of require('./craft-norms').compare(desk.metrics,type))all.push(i);
 for(const p of pictures||[])for(const i of p.issues||[])if(TELLS.has(i.kind)&&!all.some(a=>a.kind===i.kind))all.push(i);
 const stats=require('./design-tells').madeUpStats((pictures||[]).flatMap(p=>p.stats||[]),facts);
 if(stats.length)all.push({severity:'major',kind:'made-up-number',issue:'Numbers the owner never gave: '+stats.slice(0,4).join(', '),fix:'Remove these numbers (or the whole stats row). Show only numbers the owner gave.'});
 return all;
}
function major(list){return list.filter(i=>i.severity==='major')}

function fixMessage(list){
 return'Craft pass: the page still has the generic "made by AI" look. Measured on the real page:\n'+list.map((i,n)=>(n+1)+'. '+i.issue+'. Fix: '+i.fix).join('\n')+'\nFix exactly these, across every page and section where they appear. Keep all content, sections, features and data working. Do not add new boxes, labels, badges or effects while fixing. In "message", say in one sentence what you refined, in plain words (no code, files or design jargon).';
}

// The reviewer's question: would a top studio ship this, and what still looks generated?
function reviewPrompt(request,avoid=[],type=null){
 return`You are the design director of a top independent studio (the kind that makes sites like fin.ai, perflo.ai, linear.app, stripe.com). Look at these screenshots of a new website (desktop first, then phone). It was made for this request:
"${String(request||'').slice(0,1200)}"

Would your studio ship it as it is? Be strict about anything that makes it look generated by AI or built from a template, for example:
${require('./design-slop').list()}${(avoid||[]).length?'\n'+avoid.slice(0,6).map(a=>'- '+a).join('\n'):''}
${require('./craft-norms').note(type)}
Also judge it like a human creative director:
- Is there one clear design thesis, or does it feel like unrelated fashionable components?
- Is there one memorable composition or visual move that belongs specifically to THIS business/product?
- Does the page/screen have rhythm: deliberate changes in scale, density, alignment and whitespace rather than repeated same-size sections?
- Are image crops, type scale, spacing and copy density intentional enough that a designer appears to have edited them by hand?
- Has unnecessary decoration been removed, or does it keep accumulating badges, cards, icons, glows and effects?
- Do interactions feel considered and restrained rather than added everywhere?
Also: does the hero have one strong, specific idea for THIS business (not a generic layout), is the type set with care (sizes, spacing, line length), and does the page feel made by people for people?
Respond with ONLY JSON: {"ok":true} if you would ship it, or {"ok":false,"problems":["the concrete change, where on the page", ...]} with the 2 to 4 most important changes, most important first.`;
}

// Run the check. edit(message, displayText) makes one builder change and returns its result.
async function run({url,request,facts,type=null,designShots,reviewLook,edit,avoid=[],signal,onProgress=()=>{}}){
 const out={passes:0,fixed:[],remaining:[],review:null};
 if(!designShots||!url)return out;
 onProgress('Checking it looks hand-made');
 let pictures=await designShots(url());
 if(!pictures.length)return out;
 let list=found(pictures,facts,type);
 // 1. Measured giveaways: fixed, then measured again (twice at most).
 for(let round=0;round<2&&major(list).length;round++){
  if(signal&&signal.aborted)return out;
  onProgress('Making it look hand-made');
  const r=await edit(fixMessage(list.filter(i=>i.severity==='major').concat(list.filter(i=>i.severity==='minor')).slice(0,8)),'Refine the design so it looks hand-made');
  if(!r||r.unchanged||r.rolled_back)break;
  out.passes++;out.fixed.push(...major(list).map(i=>i.kind));
  pictures=await designShots(url());list=found(pictures,facts,type);
 }
 out.remaining=major(list).map(i=>i.issue);
 // 2. A design director looks at the screenshots once.
 if(reviewLook&&pictures.length&&!(signal&&signal.aborted)){
  onProgress('A design director is looking at it');
  const seen=await reviewLook({request,pictures,signal,prompt:reviewPrompt(request,avoid,type)}).catch(()=>null);
  out.review=seen?{ok:seen.ok,problems:seen.problems}:null;
  if(seen&&!seen.ok&&seen.problems.length){
   onProgress('Refining the design');
   const r=await edit('Design director review of the screenshots. Make these changes so the site looks made by a top studio, not generated:\n'+seen.problems.map((p,n)=>(n+1)+'. '+p).join('\n')+'\nKeep all content, sections, features and data working, and do not bring back the generic AI look (identical boxes, labels above headings, arrows on every button, one coloured word in headings, filler words). In "message", say in one sentence what you refined, in plain words.','Refine the design after a design review');
   if(r&&!r.unchanged&&!r.rolled_back)out.passes++;
  }
 }
 return out;
}

// The one line the owner sees.
function summary(out){
 if(!out||(!out.passes&&!out.review))return'';
 if(!out.passes)return'Checked the design for anything that looks generic: nothing to change.';
 return'Refined the design so it looks hand-made rather than generated ('+out.passes+' pass'+(out.passes>1?'es':'')+').';
}

module.exports={run,found,fixMessage,reviewPrompt,summary,TELLS};
